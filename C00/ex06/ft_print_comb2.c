#include <unistd.h>

void	ft_print(int a, int b)
{
	char	c;

	c = a / 10 + '0';
	write(1, &c, 1);
	c = a % 10 + '0';
	write(1, &c, 1);
	write(1, " ", 1);
	c = b / 10 + '0';
	write(1, &c, 1);
	c = b % 10 + '0';
	write(1, &c, 1);
	if (!(a == 98 && b == 99))
		write(1, ", ", 2);
}

void	ft_print_comb2(void)
{
	int	a;
	int	b;

	a = 100;
	while (a < 199)
	{
		b = a + 1;
		while (b < 200)
		{
			if (a < b)
				ft_print(a % 100, b % 100);
			++b;
		}
		++a;
	}
}


char	ft_is_int(char *t)
{
	int	sign;

	sign = 1 - (*t == '-') * 2;
	if (*t == '-' || *t == '+')
		t++;
	while (*t != '\0')
	{
		if (*t < '0' || *t > '9')
			return (0);
		t++;
	}
	return (1);
}

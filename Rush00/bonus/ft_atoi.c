int	ft_atoi(char *t)
{
	int	ans;
	int	sign;

	ans = 0;
	sign = 1 - (*t == '-') * 2;
	if (*t == '-' || *t == '+')
		t++;
	while (*t != '\0' && *t >= '0' && *t <= '9')
	{
		ans = ans * 10 + (*t - '0');
		t++;
	}
	return (sign * ans);
}
